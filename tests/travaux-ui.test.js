const assert = require("node:assert/strict");
const { chromium } = require("playwright");
const { spawn } = require("node:child_process");
const path = require("node:path");
const os = require("node:os");

async function run(viewport) {
  const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROME_PATH });
  try {
    const page = await browser.newPage({ viewport, serviceWorkers: "block" });
    const errors = [];
    page.on("pageerror", error => errors.push(error.message));
    await page.route("**/config.js", route => route.fulfill({ contentType: "text/javascript", body: "window.SCI_RUVELON_CONFIG = {};" }));
    await page.goto("http://127.0.0.1:8792", { waitUntil: "networkidle" });
    await page.getByRole("button", { name: "Mode apercu local" }).click();
    await page.evaluate(() => {
      localStorage.setItem("ruvelon_v3_travaux", JSON.stringify([
        { id: "one", titre: "Réfection toiture", priorite: "P1", statut: "0 - À chiffrer", montant_estime: 1000, montant_reel: 0, observations: JSON.stringify({ version_travaux: 1, annee: 2027, devis_ht: 900, notes: "Note conservée", ppi: { 2028: 1000 }, source_key: "test-one" }) },
        { id: "two", titre: "Éclairage", priorite: "P2", statut: "5 - En cours", montant_estime: 100, montant_reel: 50, observations: JSON.stringify({ version_travaux: 1, annee: 2026 }) }
      ]));
    });
    await page.reload({ waitUntil: "networkidle" });
    await page.getByRole("button", { name: "Mode apercu local" }).click();
    await page.locator('button[data-route="travaux"]').click();
    assert.match(await page.locator("#screen").innerText(), /1100.00 EUR/);
    await page.getByLabel("Année travaux").selectOption("2027");
    const visibleList = viewport.width < 768 ? page.locator(".works-panel .mobile-list") : page.locator(".works-table");
    assert.match(await visibleList.innerText(), /Réfection toiture/);
    assert.doesNotMatch(await visibleList.innerText(), /Éclairage/);
    await page.evaluate(() => App.openTravaux("one"));
    const form = page.locator("#edit-form");
    await form.locator('[name="annee_cible"]').fill("2028");
    await form.locator('[name="montant_estime"]').fill("1200");
    await form.locator('[name="devis_ht_travaux"]').fill("1100");
    await form.locator('[name="tva_travaux"]').selectOption("10");
    assert.equal(await page.locator("#modal-body").evaluate(e => e.scrollWidth > e.clientWidth + 1), false);
    await form.getByRole("button", { name: "Enregistrer" }).click();
    await page.waitForFunction(() => document.getElementById("modal").hidden);
    const row = await page.evaluate(() => JSON.parse(localStorage.getItem("ruvelon_v3_travaux")).find(t => t.id === "one"));
    const detail = JSON.parse(row.observations);
    assert.equal(detail.annee, 2028);
    assert.equal(detail.devis_ht, 1100);
    assert.equal(detail.source_key, "test-one");
    assert.equal(detail.notes, "Note conservée");
    assert.equal(row.montant_estime, 1200);
    assert.equal(detail.tva_travaux, 10);
    await page.getByLabel("Année travaux").selectOption("");
    assert.match(await visibleList.innerText(), /1320.00 EUR TTC/);
    assert.equal(await page.locator("#screen").evaluate(e => e.scrollWidth > e.clientWidth + 1), false);
    await page.screenshot({ path: path.join(os.tmpdir(), `ruvelon-travaux-${viewport.width}.png`), fullPage: true });
    const deleteButton = visibleList.getByRole("button", { name: "Supprimer", exact: true }).first();
    page.once("dialog", dialog => dialog.dismiss());
    await deleteButton.click();
    assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem("ruvelon_v3_travaux")).length), 2);
    page.once("dialog", dialog => { assert.match(dialog.message(), /Éclairage/); return dialog.accept(); });
    await deleteButton.click();
    await page.waitForFunction(() => JSON.parse(localStorage.getItem("ruvelon_v3_travaux")).length === 1);
    await page.waitForFunction(() => document.querySelector(".works-cards").textContent.includes("1200.00 EUR"));
    assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem("ruvelon_v3_travaux"))[0].id), "one");
    await page.locator('.works-panel .panel-head button').click();
    const newForm = page.locator('#edit-form');
    assert.equal(await newForm.locator('[name="origine_travaux"]').inputValue(), 'nouveau');
    assert.equal(await newForm.locator('[name="annee_cible"]').isEditable(), true);
    await newForm.locator('[name="annee_cible"]').fill('2029');
    await newForm.locator('[name="date_prevue"]').fill('2029-04-12');
    await newForm.locator('[name="montant_estime"]').fill('200');
    await newForm.locator('[name="tva_travaux"]').selectOption('20');
    await newForm.locator('[name="titre"]').fill('Fuite imprévue');
    await newForm.getByRole('button', { name: 'Enregistrer' }).click();
    await page.waitForFunction(() => document.getElementById('modal').hidden);
    let added = await page.evaluate(() => JSON.parse(localStorage.getItem('ruvelon_v3_travaux')).find(t => t.titre === 'Fuite imprévue'));
    assert.ok(added.id);
    assert.equal(added.local_id, null);
    assert.equal(added.date_prevue, '2029-04-12');
    assert.equal(JSON.parse(added.observations).annee, 2029);
    assert.equal(JSON.parse(added.observations).origine, 'nouveau');
    await page.getByLabel('Année travaux').selectOption('2029');
    assert.match(await visibleList.innerText(), /Fuite imprévue/);
    assert.match(await visibleList.innerText(), /240.00 EUR TTC/);
    const programmation = page.locator(".travaux-programmation");
    const summary = year => programmation.locator(`[data-annee="${year}"]:visible`);
    const record = () => page.evaluate(() => JSON.parse(localStorage.getItem('ruvelon_v3_travaux')).find(t=>t.titre==='Fuite imprévue'));
    const reportButton = visibleList.getByRole('button',{name:'Reporter',exact:true});
    await reportButton.click();
    assert.equal(await newForm.locator('[name="annee"]').inputValue(),'2030');
    await newForm.getByRole('button',{name:'Annuler',exact:true}).click();
    assert.deepEqual(await record(),added);
    await reportButton.click();
    await newForm.locator('[name="motif"]').fill('Décalage du chantier');
    await newForm.getByRole('button',{name:'Confirmer le report'}).click();
    await page.waitForFunction(() => document.getElementById('modal').hidden);
    const reported = await record();
    const report = JSON.parse(reported.observations).reports[0];
    assert.equal(reported.date_prevue,null);
    assert.equal(reported.statut,added.statut);
    assert.deepEqual(report.avant,{annee:2029,date:'2029-04-12'});
    assert.deepEqual(report.apres,{annee:2030,date:null});
    assert.equal(report.motif,'Décalage du chantier');
    assert.match(await summary(2029).innerText(), /1 report vers une autre année/);
    assert.doesNotMatch(await summary(2029).innerText(), /240.00 EUR/);
    assert.match(await summary(2030).innerText(), /240.00 EUR TTC/);
    await reportButton.click();
    await newForm.locator('[name="annee"]').fill('2032');
    await newForm.getByRole('button',{name:'Confirmer le report'}).click();
    await page.waitForFunction(() => document.getElementById('modal').hidden);
    assert.match(await summary(2032).innerText(), /240.00 EUR TTC/);
    for (const year of [2030,2029]) {
      await visibleList.getByRole('button',{name:'Annuler le dernier report',exact:true}).click();
      await newForm.getByRole('button',{name:'Confirmer l’annulation'}).click();
      await page.waitForFunction(() => document.getElementById('modal').hidden);
      assert.equal(JSON.parse((await record()).observations).annee,year);
    }
    assert.equal((await record()).date_prevue,'2029-04-12');
    assert.deepEqual(JSON.parse((await record()).observations).reports.map(e=>e.type),['report','report','annulation','annulation']);
    assert.doesNotMatch(await summary(2030).innerText(), /vers une autre année/);
    await page.getByLabel('Année travaux').selectOption('');
    await page.getByLabel('Origine des travaux').selectOption('base');
    assert.doesNotMatch(await visibleList.innerText(), /Fuite imprévue/);
    await page.getByLabel('Origine des travaux').selectOption('nouveau');
    assert.match(await visibleList.innerText(), /Fuite imprévue/);
    await page.evaluate(id => App.openTravaux(id), added.id);
    assert.equal(await newForm.locator('[name="annee_cible"]').inputValue(), '2029');
    await newForm.locator('[name="annee_cible"]').fill('');
    await newForm.locator('[name="date_prevue"]').fill('');
    await newForm.getByRole('button', { name: 'Enregistrer' }).click();
    await page.waitForFunction(() => document.getElementById('modal').hidden);
    added = await page.evaluate(() => JSON.parse(localStorage.getItem('ruvelon_v3_travaux')).find(t => t.titre === 'Fuite imprévue'));
    assert.equal(JSON.parse(added.observations).annee, null);
    assert.match(await visibleList.innerText(), /Date à définir/);
    await page.screenshot({ path: path.join(os.tmpdir(), `ruvelon-travaux-ajout-${viewport.width}.png`), fullPage: true });
    await page.locator('[data-route="entretien"]').click();
    await page.locator('.entretien-details .panel-head button').click();
    assert.equal(await newForm.locator('[name="rubrique_travaux"]').inputValue(), 'entretien');
    await newForm.locator('[name="titre"]').fill('Contrôle chaudière');
    await newForm.locator('[name="categorie_entretien"]').selectOption('chaudiere');
    await newForm.locator('[name="origine_travaux"]').selectOption('acte_avant_gerance');
    await newForm.locator('[name="frequence_entretien"]').selectOption('Annuel');
    await newForm.locator('[name="date_prevue"]').fill('2027-02-12');
    await newForm.locator('[name="entreprise"]').fill('Prestataire test');
    await newForm.locator('[name="montant_estime"]').fill('178');
    await newForm.getByRole('button', { name: 'Enregistrer' }).click();
    await page.waitForFunction(() => document.getElementById('modal').hidden);
    assert.match(await page.locator('#screen').innerText(), /Contrôle chaudière/);
    assert.match(await page.locator('#screen').innerText(), /Déjà acté avant ma gérance/);
    assert.match(await page.locator('#screen').innerText(), /Annuel/);
    assert.match(await page.locator('#screen').innerText(), /12\/02\/2027/);
    await page.getByLabel('Année entretien').selectOption('2027');
    assert.match(await page.locator('.entretien-budget').innerText(), /178,00\s€/);
    assert.match(await page.locator('.entretien-budget').innerText(), /213,60\s€/);
    assert.doesNotMatch(await page.locator('#screen').innerText(), /Fuite imprévue/);
    await page.getByLabel('Catégorie d’entretien').selectOption('menage');
    assert.doesNotMatch(await page.locator('#screen').innerText(), /Contrôle chaudière/);
    await page.getByLabel('Catégorie d’entretien').selectOption('');
    const savedMaintenance = await page.evaluate(() => JSON.parse(localStorage.getItem('ruvelon_v3_travaux')).find(t=>t.titre==='Contrôle chaudière'));
    assert.equal(JSON.parse(savedMaintenance.observations).entretien_categorie, 'chaudiere');
    assert.equal(JSON.parse(savedMaintenance.observations).origine, 'acte_avant_gerance');
    await page.getByRole('button',{name:'Saisir le réel : Entretien chaudière'}).click();
    assert.equal(await newForm.locator('[name="chaudiere_prevision"]').inputValue(),'178');
    await newForm.locator('[name="chaudiere_prevision"]').fill('180.5');
    assert.equal(await newForm.locator('[name="chaudiere_prevision_ttc"]').inputValue(),'216.60');
    await newForm.locator('[name="chaudiere_reel_ttc"]').fill('99.03');
    assert.equal(await newForm.locator('[name="chaudiere_reel"]').inputValue(),'82.53');
    await newForm.getByRole('button',{name:'Enregistrer'}).click();
    await page.getByRole('button',{name:'Modifier : Entretien chaudière'}).waitFor();
    assert.match(await page.locator('.entretien-budget').innerText(), /82,53\s€/);
    assert.match(await page.locator('.entretien-budget').innerText(), /99,03\s€/);
    const updated = await page.evaluate(() => {
      const docs=JSON.parse(localStorage.getItem('ruvelon_v3_documents'));
      const fiches=JSON.parse(localStorage.getItem('ruvelon_v3_travaux'));
      return {budget:JSON.parse(docs.find(d=>d.categorie==='depense_entretien').observations),fiche:fiches.find(t=>t.titre==='Contrôle chaudière')};
    });
    assert.deepEqual(updated.budget,{annee:2027,postes:{chaudiere:{prevision:180.5,reel:82.53,prevision_ttc:216.6,reel_ttc:99.03}}});
    assert.deepEqual(updated.fiche,savedMaintenance);
    assert.equal(await page.locator("#screen").evaluate(e => e.scrollWidth > e.clientWidth + 1), false);
    await page.screenshot({ path: path.join(os.tmpdir(), `ruvelon-entretien-${viewport.width}.png`) });
    await page.locator('[data-route="travaux"]').click();
    assert.doesNotMatch(await page.locator('#screen').innerText(), /Contrôle chaudière/);
    await page.evaluate(() => App.openTravaux('one'));
    await newForm.locator('[name="rubrique_travaux"]').selectOption('entretien');
    await newForm.locator('[name="categorie_entretien"]').selectOption('autre');
    await newForm.getByRole('button', { name: 'Enregistrer' }).click();
    await page.waitForFunction(() => document.getElementById('modal').hidden);
    const reclassified = await page.evaluate(() => JSON.parse(localStorage.getItem('ruvelon_v3_travaux')).find(t=>t.id==='one'));
    assert.equal(JSON.parse(reclassified.observations).rubrique, 'entretien');
    assert.equal(JSON.parse(reclassified.observations).source_key, 'test-one');
    assert.equal(reclassified.montant_estime, 1200);
    await page.locator('[data-route="entretien"]').click();
    assert.match(await page.locator('#screen').innerText(), /Réfection toiture/);
    await page.locator('[data-route="etudes"]').click();
    await page.getByRole('button',{name:'Ajouter une étude'}).click();
    await newForm.locator('[name="titre"]').fill('Diagnostic test');
    await newForm.locator('[name="description"]').fill('Identifier la cause du désordre.');
    await newForm.locator('[name="debut"]').fill('2027-02-01');
    await newForm.locator('[name="fin"]').fill('2027-01-15');
    await newForm.getByRole('button',{name:'Enregistrer'}).click();
    await page.getByText("L’échéance ne peut pas précéder le début de l’étude.").waitFor();
    await newForm.locator('[name="fin"]').fill('2027-02-15');
    await newForm.locator('[name="cout_estime"]').fill('240.50');
    await newForm.locator('[name="observations"]').fill('Prévoir une visite avec le prestataire.');
    await newForm.getByRole('button',{name:'Enregistrer'}).click();
    await page.getByText('Diagnostic test',{exact:true}).waitFor();
    assert.match(await page.locator('#screen').innerText(), /Du 01\/02\/2027 au 15\/02\/2027/);
    assert.match(await page.locator('#screen').innerText(), /240.50 EUR/);
    await page.getByText('Observations détaillées',{exact:true}).click();
    await page.getByText('Prévoir une visite avec le prestataire.',{exact:true}).waitFor();
    const study = await page.evaluate(() => JSON.parse(localStorage.getItem('ruvelon_v3_travaux')).find(t=>t.titre==='Diagnostic test'));
    assert.equal(JSON.parse(study.observations).rubrique,'etude');
    assert.equal(JSON.parse(study.observations).etude_cout_estime_ht,240.5);
    assert.equal(JSON.parse(study.observations).etude_cout_reel_ht,null);
    assert.equal(await page.locator("#screen").evaluate(e => e.scrollWidth > e.clientWidth + 1), false);
    await page.screenshot({ path: path.join(os.tmpdir(), `ruvelon-etudes-${viewport.width}.png`) });
    await page.locator('[data-route="travaux"]').click();
    assert.doesNotMatch(await page.locator('#screen').innerText(), /Diagnostic test|240.50 EUR/);
    assert.match(await page.locator('#screen').innerText(), /Fuite imprévue/);
    await page.evaluate(() => {
      const key = 'ruvelon_v3_travaux';
      const rows = JSON.parse(localStorage.getItem(key));
      rows.push(
        {id:'sol',titre:'Reprise sol communs étage',montant_estime:3000,statut:'0 - À chiffrer',observations:JSON.stringify({version_travaux:1,devis_ht:3000,devis_ttc:3390})},
        {id:'copie-sol',titre:'Sol commun étage',montant_estime:500,statut:'À étudier',observations:JSON.stringify({version_travaux:1,rubrique:'etude',etude_travaux_id:'sol'})}
      );
      localStorage.setItem(key,JSON.stringify(rows));
    });
    await page.reload({waitUntil:'networkidle'});
    await page.getByRole('button',{name:'Mode apercu local'}).click();
    await page.locator('[data-route="etudes"]').click();
    assert.match(await page.locator('#screen').innerText(), /Diagnostic test/);
    assert.doesNotMatch(await page.locator('#screen').innerText(), /Sol commun étage|Reprise sol communs étage/);
    await page.locator('[data-route="travaux"]').click();
    assert.match(await page.locator('#screen').innerText(), /Reprise sol communs étage/);
    assert.match(await visibleList.innerText(), /3390.00 EUR TTC/);
    assert.doesNotMatch(await page.locator('#screen').innerText(), /Sol commun étage/);
    assert.deepEqual(errors, []);
  } finally { await browser.close(); }
}

(async () => {
  const server = spawn(process.execPath, ["dev-server.js"], { env: { ...process.env, PORT: "8792" } });
  try {
    await new Promise((resolve, reject) => { server.stdout.once("data", resolve); server.once("error", reject); });
    await run({ width: 1440, height: 900 });
    await run({ width: 390, height: 844 });
    console.log("OK - travaux, entretien et etudes separes, saisie et filtres desktop/mobile");
  } finally { server.kill(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
